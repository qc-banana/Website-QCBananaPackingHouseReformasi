
-- =========================================
-- QC PACKING HOUSE DATABASE
-- =========================================

create table if not exists public.calibration_pg (
  id bigint generated by default as identity primary key,
  pg text not null,
  week integer not null,
  call_counts jsonb not null default '{}'::jsonb,
  total_count integer not null default 0,
  uc_count integer not null default 0,
  good_call_count integer not null default 0,
  oc_count integer not null default 0,
  uc_percent numeric(7,2) not null default 0,
  good_call_percent numeric(7,2) not null default 0,
  oc_percent numeric(7,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.calibration_ph (
  id bigint generated by default as identity primary key,
  pg text not null,
  ph text not null,
  week integer not null,
  call_counts jsonb not null default '{}'::jsonb,
  total_count integer not null default 0,
  uc_count integer not null default 0,
  good_call_count integer not null default 0,
  oc_count integer not null default 0,
  uc_percent numeric(7,2) not null default 0,
  good_call_percent numeric(7,2) not null default 0,
  oc_percent numeric(7,2) not null default 0,
  created_at timestamptz not null default now()
);

-- Aktifkan Row Level Security
alter table public.calibration_pg enable row level security;
alter table public.calibration_ph enable row level security;

-- Pengunjung dan petugas boleh membaca
create policy "Public can read PG"
on public.calibration_pg
for select
to anon, authenticated
using (true);

create policy "Public can read PH"
on public.calibration_ph
for select
to anon, authenticated
using (true);

-- Hanya akun dengan app_metadata role petugas yang boleh menulis
create policy "Petugas can insert PG"
on public.calibration_pg
for insert
to authenticated
with check (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'petugas'
);

create policy "Petugas can update PG"
on public.calibration_pg
for update
to authenticated
using (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'petugas'
)
with check (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'petugas'
);

create policy "Petugas can delete PG"
on public.calibration_pg
for delete
to authenticated
using (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'petugas'
);

create policy "Petugas can insert PH"
on public.calibration_ph
for insert
to authenticated
with check (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'petugas'
);

create policy "Petugas can update PH"
on public.calibration_ph
for update
to authenticated
using (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'petugas'
)
with check (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'petugas'
);

create policy "Petugas can delete PH"
on public.calibration_ph
for delete
to authenticated
using (
  (auth.jwt() -> 'app_metadata' ->> 'role') = 'petugas'
);
